#!/usr/bin/env python3
"""F15.1 (ticket 18): the boundary-aware single-scatter albedo table of the volumetric subsurface RT tier (--subsurface-mode rt-walk).

The walk (shaders/subsurface_walk.metal) needs, per pixel, the single-scatter albedo alpha of a homogeneous medium whose semi-infinite slab
under the engine's rough dielectric boundary (ior 1.5, GGX alpha = roughness^2) reflects the observed albedo C = the material's subsurface
colour (the OpenPBR definition, ADR-0005; the draft's Kulla-Conty inversion ignores the boundary and lands 0.4-0.8 x C).  The table is the
monotone inversion of the Mitsuba 3.9.1 measurements of tools/f15_subsurface_reference.py (`albedo-table`, `albedo-curves`: A(alpha; g,
boundary) of a 100-mfp sphere under a constant environment), per boundary roughness and anisotropy g, over a uniform grid of colours:
  value = sqrt(1 - alpha)   (smooth near alpha -> 1; a colour above the largest albedo A_max the boundary lets through stores 0 = alpha 1)
Roughness and g are interpolated linearly in the shader and clamped to the measured range: ROUGHNESS (the engine's perceptual roughness) in
[0.15, 0.7], g in [0, 0.3] (outside the range the nearest measured curve is used: declared, ticket 18).

  uv run --offline --no-project --python 3.13 --with numpy python -I tools/f15_subsurface_lut.py header [--check]
generates src/renderer/subsurface_walk_table.h from tools/f15_subsurface_albedo.json (roughness 0.35, g 0 and 0.3) and
tools/f15_subsurface_albedo_curves.json (the other roughnesses, `albedo-curves`).
"""
import argparse
import json
import math
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "tools"))
import f15_subsurface_reference as ref  # noqa: E402

HEADER_PATH = REPO / "src" / "renderer" / "subsurface_walk_table.h"
CURVES_PATH = ref.ALBEDO_CURVES_PATH
COLOUR_COUNT = 65
G_KNOTS = (0.0, 0.3)


def collect_curves():
    """{(roughness, g): curve} of the committed measurements (ior 1.5 only)."""
    out = {}
    for curve in ref.load_albedo_table()["curves"]:  # tools/f15_subsurface_albedo.json + tools/f15_subsurface_albedo_curves.json
        if abs(curve["ior"] - ref.BOUNDARY_IOR) > 1e-6 or curve["g"] not in G_KNOTS:
            continue
        roughness = round(math.sqrt(curve["alpha_b"]), 4)
        out[(roughness, curve["g"])] = curve
    return out


def table():
    curves = collect_curves()
    # a roughness enters the table only with a curve for every g knot (a measurement in progress is left out)
    roughness = sorted(r for r in {r for r, _ in curves} if all((r, g) in curves for g in G_KNOTS))
    data = []
    a_max = []
    for r in roughness:
        for g in G_KNOTS:
            curve = curves[(r, g)]
            a_max.append(ref.observed_albedo(1.0, curve))
            for i in range(COLOUR_COUNT):
                c = i / (COLOUR_COUNT - 1)
                alpha, _, _ = ref.invert_observed_albedo(c, curve)
                data.append(math.sqrt(max(1.0 - alpha, 0.0)))
    return roughness, data, a_max


def fmt(v):
    text = f"{v:.7g}"
    if "." not in text and "e" not in text and "inf" not in text:
        text += ".0"
    return text + "f"


def header_text():
    roughness, data, a_max = table()
    lines = ["#pragma once", "",
             "// GENERATED by tools/f15_subsurface_lut.py (header): do not edit.  The boundary-aware single-scatter albedo table of the",
             "// volumetric subsurface RT tier (ticket 18): layout [roughness][g][colour] of sqrt(1 - alpha) (renderer/subsurface_walk_math.h).",
             "#include \"renderer/gpu_types.h\"", "", "namespace phosphor {", "",
             f"PHOSPHOR_GPU_CONSTANT u32 kSubsurfaceTableRoughnessCount = {len(roughness)}u;",
             f"PHOSPHOR_GPU_CONSTANT u32 kSubsurfaceTableGCount = {len(G_KNOTS)}u;",
             f"PHOSPHOR_GPU_CONSTANT u32 kSubsurfaceTableColourCount = {COLOUR_COUNT}u;",
             f"PHOSPHOR_GPU_CONSTANT u32 kSubsurfaceTableSize = {len(data)}u;", ""]

    def knots(name, values):
        expr = ""
        for i in range(len(values) - 1, -1, -1):
            expr = fmt(values[i]) if i == len(values) - 1 else f"(i == {i}u ? {fmt(values[i])} : {expr})"
        return [f"inline float {name}(u32 i) {{ (void)i; return {expr}; }}"]
    lines += knots("subsurfaceTableRoughness", roughness) + knots("subsurfaceTableG", list(G_KNOTS))
    lines += ["", "// Largest observed albedo of each (roughness, g) curve (the Mitsuba plateau): a colour above it saturates (alpha = 1).",
              "// " + ", ".join(f"r{r:g} g{g:g}: {a:.4f}" for (r, g), a in zip([(r, g) for r in roughness for g in G_KNOTS], a_max)), "",
              "#ifndef __METAL_VERSION__",
              "// Host copy: uploaded once to a GPU buffer (Metal reads it as `const device float*`; shader validation corrupts program-scope arrays).",
              "inline constexpr float kSubsurfaceTableData[kSubsurfaceTableSize] = {"]
    for i in range(0, len(data), 8):
        lines.append("    " + ", ".join(fmt(v) for v in data[i:i + 8]) + ",")
    lines += ["};", "#endif", "", "} // namespace phosphor", ""]
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    h = sub.add_parser("header")
    h.add_argument("--check", action="store_true", help="fail when the committed header is stale")
    args = parser.parse_args(argv)
    text = header_text()
    if args.check:
        if HEADER_PATH.read_text() != text:
            print("subsurface_walk_table.h is stale: regenerate with tools/f15_subsurface_lut.py header", file=sys.stderr)
            return 1
        return 0
    HEADER_PATH.write_text(text)
    print(f"wrote {HEADER_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
