#!/usr/bin/env python3
"""Generate src/renderer/dfg_table.h: the split-sum DFG terms of the engine BRDF.

F13.5. For GGX with height-correlated Smith visibility V = 0.5/(gv+gl) and
Schlick Fresnel (the contract of restir_common.h diBRDF, reflection_settings
specularBRDF and the reference renderer), the directional albedo under unit
radiance is f0*A + B with A = E[w (1 - Fc)], B = E[w Fc], Fc = (1 - v.h)^5 and
w = 4 V (n.l)(v.h)/(n.h) for h drawn from the GGX normal distribution.
Nodes: NdotV = i/(N-1) (node 0 at 1e-3), roughness = j/(N-1), alpha = max(r^2,
0.002) as the engine. Deterministic Hammersley samples; no randomness.
Usage: python3 tools/dfg_table.py [--size N] [--samples S] [--out PATH]
"""
import argparse
import math
from pathlib import Path

import numpy as np


def radical_inverse(n):
    bits = np.arange(n, dtype=np.uint32)
    bits = ((bits << 16) | (bits >> 16)).astype(np.uint32)
    bits = (((bits & 0x55555555) << 1) | ((bits & 0xAAAAAAAA) >> 1)).astype(np.uint32)
    bits = (((bits & 0x33333333) << 2) | ((bits & 0xCCCCCCCC) >> 2)).astype(np.uint32)
    bits = (((bits & 0x0F0F0F0F) << 4) | ((bits & 0xF0F0F0F0) >> 4)).astype(np.uint32)
    bits = (((bits & 0x00FF00FF) << 8) | ((bits & 0xFF00FF00) >> 8)).astype(np.uint32)
    return bits.astype(np.float64) * 2.3283064365386963e-10


def dfg(nv, roughness, samples):
    a = max(roughness * roughness, 0.002); a2 = a * a
    v = np.array([math.sqrt(max(0.0, 1 - nv * nv)), 0.0, nv])
    u = (np.arange(samples) + 0.5) / samples; phi = 2 * math.pi * radical_inverse(samples)
    c = np.sqrt((1 - u) / (1 + (a2 - 1) * u)); s = np.sqrt(np.maximum(0.0, 1 - c * c))
    h = np.stack([s * np.cos(phi), s * np.sin(phi), c], 1)
    vh = h @ v; l = 2 * vh[:, None] * h - v; nl = l[:, 2]
    ok = (nl > 0) & (vh > 0)
    gv = nl * np.sqrt(nv * nv * (1 - a2) + a2); gl = nv * np.sqrt(nl * nl * (1 - a2) + a2)
    w = np.where(ok, (0.5 / np.maximum(gv + gl, 1e-5)) * 4 * vh * nl / c, 0.0)
    fc = (1 - np.clip(vh, 0, 1)) ** 5
    return float(np.mean(w * (1 - fc))), float(np.mean(w * fc))


def table(size, samples):
    rows = []
    for j in range(size):
        r = j / (size - 1)
        for i in range(size):
            nv = max(i / (size - 1), 1e-3)
            rows.append(dfg(nv, r, samples))
    return rows


def main():
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--size", type=int, default=32); p.add_argument("--samples", type=int, default=16384)
    p.add_argument("--out", type=Path, default=Path(__file__).resolve().parents[1] / "src/renderer/dfg_table.h")
    args = p.parse_args()
    rows = table(args.size, args.samples)
    body = ",\n".join("    " + ", ".join(f"{a:.8e}f, {b:.8e}f" for a, b in rows[j * args.size:(j + 1) * args.size]) for j in range(args.size))
    args.out.write_text(f'''#pragma once
// GENERATED by tools/dfg_table.py --size {args.size} --samples {args.samples}; do not edit.
// F13.5 split-sum DFG of the engine BRDF (GGX, height-correlated Smith,
// Schlick): directional albedo = f0 * A + B. Rows: roughness j/(N-1); columns:
// NdotV i/(N-1) (node 0 evaluated at 1e-3). Shared by C++ and MSL.
#include "renderer/gpu_types.h"
namespace phosphor {{
PHOSPHOR_GPU_CONSTANT u32 DfgTableSize = {args.size};
PHOSPHOR_GPU_CONSTANT float DfgTable[{args.size * args.size * 2}] = {{
{body}
}};
// Bilinear lookup; component 0 = A (scale of f0), 1 = B (bias).
inline float dfgTableLookup(float nv, float roughness, u32 component) {{
    const float n = float(DfgTableSize - 1);
    const float x = (nv > 0 ? (nv < 1 ? nv : 1.0f) : 0.0f) * n, y = (roughness > 0 ? (roughness < 1 ? roughness : 1.0f) : 0.0f) * n;
    const u32 x0 = u32(x) < DfgTableSize - 1 ? u32(x) : DfgTableSize - 2, y0 = u32(y) < DfgTableSize - 1 ? u32(y) : DfgTableSize - 2;
    const float fx = x - float(x0), fy = y - float(y0);
    const float v00 = DfgTable[(y0 * DfgTableSize + x0) * 2 + component], v10 = DfgTable[(y0 * DfgTableSize + x0 + 1) * 2 + component];
    const float v01 = DfgTable[((y0 + 1) * DfgTableSize + x0) * 2 + component], v11 = DfgTable[((y0 + 1) * DfgTableSize + x0 + 1) * 2 + component];
    return (v00 * (1 - fx) + v10 * fx) * (1 - fy) + (v01 * (1 - fx) + v11 * fx) * fy;
}}
}} // namespace phosphor
''')
    print(f"wrote {args.out} ({args.size}x{args.size}, {args.samples} samples per node)")


if __name__ == "__main__":
    main()
