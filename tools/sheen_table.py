#!/usr/bin/env python3
"""Generate src/renderer/sheen_table.h: the directional albedo E(NdotV, sheenRoughness) of the Charlie sheen BRDF.

F15.3 (ticket 10).  KHR_materials_sheen (ratified text, non-normative notes of research/khr-materials.md section 3)
scales the material under the sheen by `1 - max3(sheenColor) * E(V.N, sheenRoughness)`, and the sheen environment
term is `sheenColor * E * radiance`; the specification ships no table ("Phosphor must bake its own E"), so this
tool is the table's provenance (decision 06, "generated by a Phosphor tool with a negative control").

E is the Fresnel-free albedo of the sheen BRDF f = D_charlie * V_charlie under unit radiance:
  E(mu, r) = integral over the hemisphere of D_charlie(N.H) V_charlie(N.V, N.L) N.L dwi,   wo at N.V = mu
with, for alpha = r * r and inv_r = 1 / alpha (the specification's alpha_g):
  D_charlie = (2 + inv_r) sin(theta_h)^inv_r / (2 pi)
  V_charlie = 1 / ((1 + Lambda(N.V) + Lambda(N.L)) 4 N.V N.L),  Lambda the Estevez-Kulla fit of the notes.
The stored value is min(E, 1): with the Estevez-Kulla visibility fit the Charlie lobe is NOT energy conserving at
grazing views of narrow lobes (E reaches 2.9 at N.V = 1e-3, roughness 0.07; the Sample Renderer's unorm LUT
saturates the same way), and `1 - max3(sheenColor) E` would turn negative.  The clamp is part of the model
(`E_CLAMP`), mirrored by the reference, and only touches N.V below about 0.05 at the narrowest lobes.
Nodes: NdotV = i/(N-1) (node 0 at 1e-3), sheenRoughness = j/(N-1); roughness is clamped to [0.07, 1] (the
declared lower bound: alpha 0.0049, a lobe about 0.07 rad wide; below it the table repeats row 0.07), the
convention of tools/f15_reference.py `SHEEN_MIN_ROUGHNESS`.  The layout, the macros and the lookup follow
src/renderer/dfg_table.h (read through a GPU buffer by fragment functions, see
docs/research/2026-11-13-f15-shader-validation-constant-arrays.md).

Generation integrates over the half-vector (dwi = 4 (wo.h) dh, Gauss-Legendre in cos(theta_h) x midpoint in
phi); it is fully deterministic (no random numbers).  `--check` has three parts:
  1. regeneration: the committed header must equal a fresh run with the parameters it records;
  2. independent integration: a separately written Charlie BRDF integrated in the hemisphere of the INCIDENT
     direction (midpoint product rule in theta_i x phi_i, a different parametrisation, different nodes and a
     different code path) must agree with the committed table within INDEPENDENT_TOLERANCE (absolute) at a
     fixed set of nodes, and the table must be in [0, 1] (the albedo scaling would otherwise go negative);
  3. the negative control (`--check --corrupt`, always run by `--check`): one perturbed entry must make the
     independent check FAIL; a check that accepts it would be useless.
Usage: python3 tools/sheen_table.py [--size N] [--out PATH]      (write)
       python3 tools/sheen_table.py --check [--out PATH]          (verify the committed header)
"""
import argparse
import math
import re
import sys
from pathlib import Path

import numpy as np

MIN_ROUGHNESS = 0.07
MIN_MU = 1e-3
E_CLAMP = 1.0  # the albedo is stored as min(E, E_CLAMP)
INDEPENDENT_TOLERANCE = 2e-3  # absolute, on E in [0, 1]
REGENERATION_TOLERANCE = 5e-7  # absolute: libm/numpy last-digit differences, never a modelling difference
DEFAULT_SIZE = 64
GENERATOR_NODES = (256, 256)  # (Gauss-Legendre nodes in cos(theta_h), phi midpoint nodes)
HEADER = Path(__file__).resolve().parents[1] / "src/renderer/sheen_table.h"


# --- the Charlie BRDF (generator form: half-vector parametrisation) ------------------

def _fit(x, alpha):
    """l(x, alpha_g) of the specification notes (the Estevez-Kulla fit), element-wise on x in [0, 1]."""
    t = (1.0 - alpha) ** 2
    a = 21.5473 + (25.3245 - 21.5473) * t
    b = 3.82987 + (3.32435 - 3.82987) * t
    c = 0.19823 + (0.16801 - 0.19823) * t
    d = -1.97760 + (-1.27393 + 1.97760) * t
    e = -4.32054 + (-4.85967 + 4.32054) * t
    return a / (1.0 + b * np.power(x, c)) + d * x + e


def _lambda(cos_theta, alpha):
    x = np.abs(cos_theta)
    inner = np.exp(_fit(np.minimum(x, 0.5), alpha))
    outer = np.exp(2.0 * _fit(0.5, alpha) - _fit(np.clip(1.0 - x, 0.0, 1.0), alpha))
    return np.where(x < 0.5, inner, outer)


def sheen_alpha(roughness):
    r = min(max(float(roughness), MIN_ROUGHNESS), 1.0)
    return r * r


def albedo_half_vector(mu, roughness, nodes=GENERATOR_NODES):
    """E(mu, roughness) by quadrature over the half-vector hemisphere (the generator)."""
    n_c, n_phi = nodes
    alpha = sheen_alpha(roughness)
    inv = 1.0 / alpha
    x, w = np.polynomial.legendre.leggauss(n_c)
    c = 0.5 * (x + 1.0)
    w = 0.5 * w
    phi = (np.arange(n_phi) + 0.5) * (2.0 * math.pi / n_phi)
    s = np.sqrt(np.maximum(1.0 - c * c, 0.0))
    d = (2.0 + inv) * np.power(1.0 - c * c, 0.5 * inv) / (2.0 * math.pi)
    mu = max(float(mu), MIN_MU)
    wo = np.array([math.sqrt(max(0.0, 1.0 - mu * mu)), 0.0, mu])
    vh = s[:, None] * np.cos(phi)[None, :] * wo[0] + c[:, None] * wo[2]
    nl = 2.0 * vh * c[:, None] - wo[2]
    valid = (nl > 1e-9) & (vh > 0.0)
    denominator = (1.0 + _lambda(mu, alpha) + _lambda(np.maximum(nl, 1e-9), alpha)) * 4.0 * mu
    # D V N.L dwi with V N.L = 1 / denominator, dwi = 4 (wo.h) dh and dh = dc dphi.
    integrand = np.where(valid, d[:, None] * 4.0 * vh / denominator, 0.0)
    return float(np.sum(integrand.mean(axis=1) * 2.0 * math.pi * w))


def table(size=DEFAULT_SIZE, nodes=GENERATOR_NODES):
    """size x size values: rows = roughness j/(size-1), columns = N.V i/(size-1)."""
    rows = []
    for j in range(size):
        for i in range(size):
            rows.append(min(albedo_half_vector(i / (size - 1), j / (size - 1), nodes), E_CLAMP))
    return rows


# --- the independent integration (separately written, incident-direction parametrisation) ----

def _independent_lambda(cos_theta, roughness):
    """Lambda of the notes, written again with explicit mix(): np.piecewise on |cos|."""
    alpha_g = min(max(float(roughness), MIN_ROUGHNESS), 1.0) ** 2
    omas = (1.0 - alpha_g) * (1.0 - alpha_g)
    mix = lambda p, q: p * (1.0 - omas) + q * omas  # noqa: E731
    coeff = [mix(21.5473, 25.3245), mix(3.82987, 3.32435), mix(0.19823, 0.16801), mix(-1.97760, -1.27393),
             mix(-4.32054, -4.85967)]

    def l_of(x):
        x = np.asarray(x, dtype=np.float64)
        return coeff[0] / (1.0 + coeff[1] * x ** coeff[2]) + coeff[3] * x + coeff[4]

    cosine = np.abs(np.asarray(cos_theta, dtype=np.float64))
    low = l_of(0.5)
    return np.piecewise(cosine, [cosine < 0.5], [lambda x: np.exp(l_of(x)), lambda x: np.exp(2.0 * low - l_of(1.0 - x))])


def albedo_incident(mu, roughness, nodes=(1024, 512)):
    """E(mu, roughness) by the midpoint rule over the incident hemisphere (theta_i, phi_i): sum of
    D(N.H) V(N.V, N.L) N.L sin(theta_i) over the cells, from the vectors wo, wi (no half-vector measure)."""
    n_theta, n_phi = nodes
    r = min(max(float(roughness), MIN_ROUGHNESS), 1.0)
    inv = 1.0 / (r * r)
    theta = (np.arange(n_theta) + 0.5) * (0.5 * math.pi / n_theta)
    phi = (np.arange(n_phi) + 0.5) * (2.0 * math.pi / n_phi)
    mu = max(float(mu), MIN_MU)
    wo = np.array([math.sqrt(max(0.0, 1.0 - mu * mu)), 0.0, mu])
    cos_i, sin_i = np.cos(theta)[:, None], np.sin(theta)[:, None]
    wi = np.stack([sin_i * np.cos(phi)[None, :], sin_i * np.sin(phi)[None, :], cos_i * np.ones((1, n_phi))], axis=-1)
    h = wi + wo
    h = h / np.linalg.norm(h, axis=-1, keepdims=True)
    sin_h = np.sqrt(np.maximum(1.0 - h[..., 2] ** 2, 0.0))
    d = (2.0 + inv) * sin_h ** inv / (2.0 * math.pi)
    visibility = 1.0 / ((1.0 + _independent_lambda(mu, r) + _independent_lambda(cos_i, r)) * 4.0 * mu * cos_i)
    cell = (0.5 * math.pi / n_theta) * (2.0 * math.pi / n_phi) * sin_i
    return float(np.sum(d * visibility * cos_i * cell))


# --- header I/O ----------------------------------------------------------------------

def render_header(size, nodes, rows):
    body = ",\n".join("    " + ", ".join(f"{v:.8e}f" for v in rows[j * size:(j + 1) * size]) for j in range(size))
    return f'''#pragma once
// GENERATED by tools/sheen_table.py --size {size}; do not edit.
// F15.3 (ticket 10) directional albedo E(N.V, sheenRoughness) of the Charlie sheen BRDF (D_charlie * V_charlie,
// Fresnel-free, stored as min(E, 1)), as the specification's albedo scaling needs: base *= 1 - max3(sheenColor) * E. Rows: sheen
// roughness j/(N-1) (clamped to [0.07, 1]); columns: N.V i/(N-1) (node 0 evaluated at 1e-3). Generated by
// half-vector quadrature ({nodes[0]} x {nodes[1]} nodes) and checked by an independent incident-direction
// integration (tools/sheen_table.py --check). Shared by C++ and MSL.
#include "renderer/gpu_types.h"
namespace phosphor {{
PHOSPHOR_GPU_CONSTANT u32 SheenTableSize = {size};
PHOSPHOR_GPU_CONSTANT float SheenTable[{size * size}] = {{
{body}
}};
#if defined(__METAL_VERSION__)
#define PHOSPHOR_SHEEN_TABLE const constant float*
#else
#define PHOSPHOR_SHEEN_TABLE const float*
#endif
// Bilinear lookup on any copy of the table: the program-scope array above or a GPU buffer holding the same values
// (fragment functions read the buffer referenced by FrameConstants: MTL_SHADER_VALIDATION corrupts their reads of
// program-scope constant arrays). Same node convention as dfgTableLookup; the result is E in [0, 1].
inline float sheenTableLookup(PHOSPHOR_SHEEN_TABLE table, float nv, float roughness) {{
    const float n = float(SheenTableSize - 1);
    const float x = (nv > 0 ? (nv < 1 ? nv : 1.0f) : 0.0f) * n, y = (roughness > 0 ? (roughness < 1 ? roughness : 1.0f) : 0.0f) * n;
    const u32 x0 = u32(x) < SheenTableSize - 1 ? u32(x) : SheenTableSize - 2, y0 = u32(y) < SheenTableSize - 1 ? u32(y) : SheenTableSize - 2;
    const float fx = x - float(x0), fy = y - float(y0);
    const float v00 = table[y0 * SheenTableSize + x0], v10 = table[y0 * SheenTableSize + x0 + 1];
    const float v01 = table[(y0 + 1) * SheenTableSize + x0], v11 = table[(y0 + 1) * SheenTableSize + x0 + 1];
    return (v00 * (1 - fx) + v10 * fx) * (1 - fy) + (v01 * (1 - fx) + v11 * fx) * fy;
}}
inline float sheenTableLookup(float nv, float roughness) {{
    return sheenTableLookup(SheenTable, nv, roughness);
}}
}} // namespace phosphor
'''


def parse_header(path):
    """(size, values[size, size], generator nodes) of a sheen_table.h."""
    text = Path(path).read_text()
    size = int(re.search(r"SheenTableSize\s*=\s*(\d+)\s*;", text).group(1))
    start = text.index("SheenTable[")
    body = text[text.index("{", start) + 1:text.index("};", start)]
    values = [float(v) for v in re.findall(r"[-+]?(?:\d+\.\d*|\.\d+)(?:[eE][-+]?\d+)?(?=f\b)", body)]
    if len(values) != size * size:
        raise ValueError(f"{path}: expected {size * size} sheen values, parsed {len(values)}")
    nodes = tuple(int(v) for v in re.search(r"\((\d+) x (\d+) nodes\)", text).groups())
    return size, np.asarray(values, dtype=np.float64).reshape(size, size), nodes


# --- the checks ----------------------------------------------------------------------

def check_nodes(size):
    """Fixed verification nodes (row = roughness, column = N.V): every roughness decade and a spread of N.V
    including both ends; deterministic, a subset of the table's own nodes."""
    rows = sorted({0, round(0.07 * (size - 1)), round(0.1 * (size - 1)), round(0.3 * (size - 1)),
                   round(0.5 * (size - 1)), round(0.75 * (size - 1)), size - 1})
    cols = sorted({0, 1, round(0.1 * (size - 1)), round(0.25 * (size - 1)), round(0.5 * (size - 1)),
                   round(0.75 * (size - 1)), size - 1})
    return [(j, i) for j in rows for i in cols]


def independent_check(values, nodes=None, tolerance=INDEPENDENT_TOLERANCE, integrate=albedo_incident):
    """Failures of `values` ([size, size]) against the independent integration: a list of strings, empty = pass."""
    size = values.shape[0]
    failures = []
    if not np.all(np.isfinite(values)) or values.min() < 0.0 or values.max() > 1.0:
        failures.append(f"table outside [0, 1]: min {values.min():.6f} max {values.max():.6f}")
    for j, i in nodes or check_nodes(size):
        reference = min(integrate(i / (size - 1), j / (size - 1)), E_CLAMP)
        if abs(values[j, i] - reference) > tolerance:
            failures.append(f"row {j} column {i}: table {values[j, i]:.6f} vs independent {reference:.6f}")
    return failures


def corrupt(values, row=None, column=None, delta=0.05):
    """A copy of the table with one entry perturbed by `delta` (the negative control).  Default: the first
    verification node, so the control is guaranteed to be on a checked entry."""
    out = values.copy()
    j, i = (row, column) if row is not None and column is not None else check_nodes(values.shape[0])[len(check_nodes(values.shape[0])) // 2]
    out[j, i] = min(1.0, out[j, i] + delta) if out[j, i] + delta <= 1.0 else out[j, i] - delta
    return out


def command_check(path):
    size, values, nodes = parse_header(path)
    print(f"{path}: {size}x{size}, generator nodes {nodes}")
    status = 0
    fresh = np.asarray(table(size, nodes), dtype=np.float64).reshape(size, size)
    worst = float(np.abs(fresh - values).max())
    text_equal = render_header(size, nodes, list(fresh.reshape(-1))) == Path(path).read_text()
    print(f"regeneration: max |fresh - committed| = {worst:.3e} (tolerance {REGENERATION_TOLERANCE:.0e}), "
          f"byte-identical text: {text_equal}")
    if worst > REGENERATION_TOLERANCE:
        print("FAIL: the committed table is not what the tool generates")
        status = 1
    failures = independent_check(values)
    print(f"independent integration at {len(check_nodes(size))} nodes (tolerance {INDEPENDENT_TOLERANCE}): "
          f"{'PASS' if not failures else 'FAIL'}")
    for line in failures:
        print("  " + line)
    status = status or (1 if failures else 0)
    control = independent_check(corrupt(values))
    print(f"negative control (one entry perturbed by 0.05): {'FAILS as required' if control else 'PASSES (check is useless)'}")
    if not control:
        status = 1
    print("OK" if status == 0 else "FAILED")
    return status


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--size", type=int, default=DEFAULT_SIZE)
    p.add_argument("--out", type=Path, default=HEADER)
    p.add_argument("--check", action="store_true", help="verify the header at --out (regeneration, independent integration, negative control)")
    args = p.parse_args(argv)
    if args.check:
        return command_check(args.out)
    rows = table(args.size)
    args.out.write_text(render_header(args.size, GENERATOR_NODES, rows))
    print(f"wrote {args.out} ({args.size}x{args.size}, half-vector quadrature {GENERATOR_NODES[0]}x{GENERATOR_NODES[1]})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
