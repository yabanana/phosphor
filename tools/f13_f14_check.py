def reference_role(case):
    """Reference each case is judged against, as the F13/F14 plans declare it.

    independent-clip: the product output must match an independent converged
      clip (F13 custom denoise, AO, probes, MetalFX); pending until supplied.
    numerical: F14 sparse numerical oracles (LUT integrals, Beer-Lambert,
      solar clock); the volume evidence gates the case.
    full-rate-pair: temporal reconstruction against its full-rate control
      (F14 clouds); the pair metrics gate the case.
    repeatability-pair: a second identical run (F14.4 day/night); its frames
      must equal the first run's bit for bit, and its numerical oracle passes.
    control: raw inputs, higher-sample controls, SSR/probe-capture and
      full-rate controls; metrics are reported, they do not gate.
    functional: no capture; functional and negative checks only.
    """
    name=case["name"]
    if not case.get("capture",True):return "functional"
    if case.get("raw_diagnostic") or case.get("probe_capture") or case.get("reference_kind"):return "control"
    if name=="mirror-ssr" or name.endswith("-raw"):return "control"
    if case.get("repeat_of"):return "repeatability-pair"
    if case["phase"]=="F14":return "full-rate-pair" if case.get("quality_pair") else "numerical"
    return "independent-clip"


def gating_passed(result,role,case=None):
    """True when the evidence this case's role requires exists and passes.

    A pair negative (expected_pair_failure) must run cleanly and its computed
    pair metrics must FAIL against the same control.
    """
    case=case or {}
    if not result.get("functional_passed",False):return False
    if role=="independent-clip" and not result.get("independent_metrics",{}).get("passed",False):return False
    if role=="full-rate-pair":
        metrics=result.get("control_metrics",{})
        if case.get("expected_pair_failure"):
            if "regions" not in metrics or metrics.get("passed") is not False:return False
        elif not metrics.get("passed",False):return False
    if case.get("coverage_check") and not result.get("coverage",{}).get("passed",False):return False
    if role=="repeatability-pair" and not result.get("repeatability",{}).get("passed",False):return False
    return result.get("numerical",{}).get("passed",True) and result.get("external_numerical",{}).get("passed",True)


def coverage_evidence(control,candidate,config):
    """Per-frame covered fraction (T < threshold, channel 0) in every ROI."""
    refs,ids=clip_files(control);cands,candidate_ids=clip_files(candidate)
    if ids!=candidate_ids:raise ValueError("coverage frames differ between control and candidate")
    threshold=COVERAGE["transmittance_threshold"];limit=COVERAGE["max_fraction_delta"];rois={}
    for ref_path,cand_path,frame in zip(refs,cands,ids):
        ref,cand=read_pfm(ref_path),read_pfm(cand_path)
        if (ref.width,ref.height)!=(cand.width,cand.height):raise ValueError("coverage extent differs")
        for roi in config["rois"]:
            x,y,w,h=bounds(roi,ref.width,ref.height);covered=[0,0]
            for yy in range(y,y+h):
                base=(yy*ref.width+x)*3
                for i in range(base,base+w*3,3):
                    covered[0]+=ref.rgb[i]<threshold;covered[1]+=cand.rgb[i]<threshold
            a,b=covered[0]/(w*h),covered[1]/(w*h);entry=rois.setdefault(roi["name"],{"max_delta":0.0,"frame":None,"max_full_rate_coverage":0.0})
            entry["max_full_rate_coverage"]=max(entry["max_full_rate_coverage"],a)
            if abs(b-a)>=entry["max_delta"]:entry.update(max_delta=abs(b-a),frame=frame,full_rate=a,reconstructed=b)
    worst=max(v["max_delta"] for v in rois.values())
    return {"threshold":threshold,"limit":limit,"frames":len(ids),"rois":rois,"max_delta":worst,
            "exercised":any(v["max_full_rate_coverage"]>0 for v in rois.values()),"passed":worst<=limit and any(v["max_full_rate_coverage"]>0 for v in rois.values())}


def repeatability(first,second,frames):
    """Frame-by-frame comparison of two runs of the same frozen case."""
    a=sorted(Path(first).glob("frame-*.pfm"));b=sorted(Path(second).glob("frame-*.pfm"))
    if len(a)!=frames or [p.name for p in a]!=[p.name for p in b]:raise ValueError("repeat runs captured different frame sets")
    differing=[];worst=0.0
    for x,y in zip(a,b):
        if x.read_bytes()==y.read_bytes():continue
        ix,iy=read_pfm(x),read_pfm(y)
        if (ix.width,ix.height)!=(iy.width,iy.height):raise ValueError("repeat extent differs")
        d=max(abs(float(p)-float(q)) for p,q in zip(ix.rgb,iy.rgb));worst=max(worst,d);differing.append(x.name)
    return {"frames":frames,"bit_identical_frames":frames-len(differing),"differing_frames":differing[:16],
            "max_abs_difference":worst,"passed":not differing}


